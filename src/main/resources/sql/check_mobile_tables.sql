-- =====================================================================

-- 1. Bảng / sequence đã tạo đủ chưa (phải ra 4 bảng + 2 sequence)
SELECT OBJECT_TYPE, OBJECT_NAME, STATUS FROM USER_OBJECTS
 WHERE OBJECT_NAME LIKE 'MB\_%' ESCAPE '\' AND OBJECT_TYPE IN ('TABLE', 'SEQUENCE')
 ORDER BY 1, 2;

-- 2. Cột Phase 4 đã có chưa (LANG, REF_EXTRA, DEDUP_KEY)
SELECT TABLE_NAME, COLUMN_NAME FROM USER_TAB_COLUMNS
 WHERE (TABLE_NAME = 'MB_DEVICE' AND COLUMN_NAME = 'LANG')
    OR (TABLE_NAME = 'MB_NOTIFICATION' AND COLUMN_NAME IN ('REF_EXTRA', 'DEDUP_KEY'));

-- 3. Thiết bị đã đăng nhập app
SELECT DEVICE_ID, PERSON_ID, PLATFORM, APP_VERSION, LANG, ACTIVITY, FCM_TOKEN,
       TO_CHAR(LAST_LOGIN_DATE, 'DD/MM/YYYY HH24:MI') AS LAST_LOGIN
  FROM MB_DEVICE ORDER BY LAST_LOGIN_DATE DESC;

-- 4. Refresh token (mỗi lần refresh: token cũ REVOKED_YN = 'Y', REPLACED_BY = token mới)
SELECT TOKEN_NO, USER_NAME, DEVICE_ID, REVOKED_YN, REPLACED_BY,
       TO_CHAR(CREATE_DATE, 'DD/MM/YYYY HH24:MI:SS') AS CREATED,
       TO_CHAR(EXPIRE_DATE, 'DD/MM/YYYY') AS EXPIRES
  FROM MB_REFRESH_TOKEN ORDER BY TOKEN_NO DESC;

-- 5. Thông báo đã tạo
SELECT NOTI_NO, PERSON_ID, NOTI_TYPE, TITLE, BODY, REF_TYPE, REF_ID, REF_EXTRA, READ_YN, PUSH_YN,
       TO_CHAR(CREATE_DATE, 'DD/MM/YYYY HH24:MI:SS') AS CREATED
  FROM MB_NOTIFICATION ORDER BY NOTI_NO DESC;

-- 6. Đơn test vừa tạo từ app (thay :personId)
SELECT APPLY_NO, LEAVE_TYPE_CODE, TO_CHAR(LEAVE_FROM_TIME, 'DD/MM/YYYY HH24:MI') FROM_TIME,
       APPLY_LENGTH, AFFIRM_FLAG, CREATED_IP
  FROM ESS_LEAVE_APPLY_TB WHERE PERSON_ID = :personId ORDER BY CREATE_DATE DESC;

SELECT APPLY_NO, TO_CHAR(APPLY_OT_DATE, 'DD/MM/YYYY') OT_DATE, OT_APPLY_HOUR, AFFIRM_FLAG
  FROM ESS_APPLY_OT WHERE PERSON_ID = :personId ORDER BY CREATE_DATE DESC;

-- 7. Tuyến duyệt của 1 đơn (ACTIVITY = 0 là dòng người duyệt đang thấy trong hộp duyệt)
SELECT APPLY_NO, AFFIRM_LEVEL, AFFIRM_PERSON_ID, AFFIRM_FLAG, APPLY_AFFIRM_FLAG, ACTIVITY,
       TO_CHAR(CREATE_DATE, 'DD/MM/YYYY HH24:MI') CREATED
  FROM SY_AFFIRM_EMAIL WHERE APPLY_NO = :applyNo ORDER BY AFFIRM_LEVEL;
